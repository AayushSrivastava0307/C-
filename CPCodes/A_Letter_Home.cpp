void solve() 
{
    int n, s;
    cin>>n>>s;
    vector<int> v(n);
    for(auto &e:v) cin>>e;
    cout<<v[n-1]-v[0]+min(abs(s-v[0]),abs(s-v[n-1]))<<endl;
}
 
 
