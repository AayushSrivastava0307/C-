void solve()
{
 
    string s;
    cin>>s;
    stack<char> sk;
    for(auto e:s){
        if(sk.empty()){
            sk.push(e);
            continue;
        }
        if(!sk.empty() && sk.top()==e) sk.pop();
        else sk.push(e);
    }
    string ans=sk.empty()?"Yes":"No";
    cout<<ans<<endl;
 
}
 
 
 
signed main()
{
 
    ios_base::sync_with_stdio(false);
    cin.tie(nullptr);
 
    int tc=1;
    // cin>>tc;
 
    while(tc--)
    {
        solve();
    }
    return 0;
}