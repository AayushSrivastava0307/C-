void solve()
{
 
    int n; cin>>n;
    vector<int> v(n);
    for(auto &e:v) cin>>e;
    int barrier=abs(v[0]);
    int cnt=0;
    for(int i=1;i<n;i++){
        if(abs(v[i])<barrier) cnt++;
    }
    if(cnt<=((n)/2)) cout<<"YES"<<endl;
    else cout<<"NO"<<endl;
 
}
 
 
 
signed main()
{
 
    ios_base::sync_with_stdio(false);
    cin.tie(nullptr);
 
    int tc=1;
    cin>>tc;
 
    while(tc--)
    {
        solve();
    }
    return 0;
}